/**
 * Deploys the sample contracts to testnet and records their IDs in
 * packages/contract-loader/src/fixtures/deployments.json.
 *
 *   pnpm contracts:deploy
 *
 * Testnet is reset periodically; re-run this script after a reset. It uses a
 * fresh, friendbot-funded throwaway account every time and never needs a
 * secret from you. Override the network with STELLAR_RPC_URL and
 * STELLAR_NETWORK_PASSPHRASE (e.g. for a local quickstart node).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash, randomBytes } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Address, Keypair, Operation, TransactionBuilder, nativeToScVal, rpc, type xdr, scValToNative } from "@stellar/stellar-sdk";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const RPC_URL = process.env.STELLAR_RPC_URL ?? "https://soroban-testnet.stellar.org";
const PASSPHRASE = process.env.STELLAR_NETWORK_PASSPHRASE ?? "Test SDF Network ; September 2015";
const server = new rpc.Server(RPC_URL, { allowHttp: RPC_URL.startsWith("http://") });

async function submit(signer: Keypair, op: xdr.Operation): Promise<rpc.Api.GetSuccessfulTransactionResponse> {
  const account = await server.getAccount(signer.publicKey());
  const tx = new TransactionBuilder(account, { fee: "1000000", networkPassphrase: PASSPHRASE }).addOperation(op).setTimeout(60).build();
  const prepared = await server.prepareTransaction(tx);
  prepared.sign(signer);
  const sent = await server.sendTransaction(prepared);
  if (sent.status === "ERROR") throw new Error(`send failed: ${JSON.stringify(sent.errorResult?.toJson?.() ?? sent)}`);
  const result = await server.pollTransaction(sent.hash, { attempts: 30 });
  if (result.status !== rpc.Api.GetTransactionStatus.SUCCESS) {
    throw new Error(`transaction ${sent.hash} failed with status ${result.status}`);
  }
  return result as rpc.Api.GetSuccessfulTransactionResponse;
}

async function deploy(signer: Keypair, wasmFile: string, constructorArgs: xdr.ScVal[]) {
  const wasm = readFileSync(join(root, "contracts/artifacts", wasmFile));
  const wasmHash = createHash("sha256").update(wasm).digest();
  console.log(`  uploading ${wasmFile} (${wasm.length} bytes)…`);
  await submit(signer, Operation.uploadContractWasm({ wasm }));
  console.log("  creating contract…");
  const created = await submit(
    signer,
    Operation.createCustomContract({
      address: new Address(signer.publicKey()),
      wasmHash,
      salt: randomBytes(32),
      constructorArgs,
    }),
  );
  const contractId = Address.fromScVal(created.returnValue!).toString();
  console.log(`  → ${contractId}`);
  return { contractId, wasmHash: wasmHash.toString("hex") };
}

function invoke(contract: string, fn: string, args: xdr.ScVal[]) {
  return Operation.invokeContractFunction({ contract, function: fn, args });
}

async function main() {
  const deployer = Keypair.random();
  const holder = Keypair.random();
  console.log(`Network: ${RPC_URL}`);
  console.log(`Funding deployer ${deployer.publicKey()} and holder ${holder.publicKey()} via friendbot…`);
  await server.fundAddress(deployer.publicKey());
  await server.fundAddress(holder.publicKey());

  const owner = new Address(deployer.publicKey()).toScVal();
  console.log("Deploying counter…");
  const counter = await deploy(deployer, "counter.wasm", [owner]);
  for (const step of [1, 5]) {
    await submit(deployer, invoke(counter.contractId, "increment_by", [nativeToScVal(step, { type: "u32" })]));
  }

  console.log("Deploying sample-token…");
  const token = await deploy(deployer, "sample_token.wasm", [
    owner,
    nativeToScVal(7, { type: "u32" }),
    nativeToScVal("Playground Token", { type: "string" }),
    nativeToScVal("PLAY", { type: "string" }),
  ]);
  const mint = await submit(
    deployer,
    invoke(token.contractId, "mint", [new Address(holder.publicKey()).toScVal(), nativeToScVal(1_000_0000000n, { type: "i128" })]),
  );
  console.log(`  minted 1000 PLAY to holder (ledger ${mint.ledger}, return ${scValToNative(mint.returnValue!)})`);

  const deployments = {
    $comment: "Generated by `pnpm contracts:deploy`. Testnet resets periodically; re-run the script after a reset.",
    network: "testnet",
    rpcUrl: RPC_URL,
    deployedAt: new Date().toISOString(),
    accounts: { owner: deployer.publicKey(), holder: holder.publicKey() },
    contracts: { counter, "sample-token": token },
  };
  const out = join(root, "packages/contract-loader/src/fixtures/deployments.json");
  writeFileSync(out, JSON.stringify(deployments, null, 2) + "\n");
  console.log(`Wrote ${out}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
