/** Pretty JSON for files; deterministic key order keeps diffs readable. */
export function scenarioToJson(scenario: Scenario): string {
  return JSON.stringify(scenario, null, 2) + "\n";
}

function argsXdrFor(scenario: Scenario): string[] {
  if (scenario.recorded?.argsXdr) return scenario.recorded.argsXdr;
  const spec = scenario.contract.spec;
  if (!spec) throw new Error("Scenario has neither recorded arguments nor a spec to encode them with.");
  const r = encodeArgs(findFunction(spec, scenario.invocation.method), scenario.invocation.args, spec);
  if (!r.ok) throw new Error(`Scenario arguments are invalid: ${r.errors.map((e) => `${e.path}: ${e.message}`).join("; ")}`);
  return r.values.map((v) => v.toXdr("base64"));
}

function tsString(s: string): string {
  return JSON.stringify(s);
}

function commentBlock(text: string, indent = ""): string {
  return text
    .split("\n")
    .map((l) => `${indent}// ${l}`.trimEnd())
    .join("\n");
}

/**
 * Generates a self-contained Vitest test that replays the scenario with only
 * `@stellar/stellar-sdk`, so it can run in any project's CI.
 */
export function scenarioToVitest(scenario: Scenario): string {
  const argsXdr = argsXdrFor(scenario);
  const e = scenario.expect ?? {};
  const fn = scenario.contract.spec?.functions.find((f) => f.name === scenario.invocation.method);
  const rec = scenario.recorded?.report;
  const lines: string[] = [];
  const assertions: string[] = [];

  if (e.status === "error" || (e.contractErrorCode !== undefined && e.status !== "success")) {
    assertions.push(`    expect(rpc.Api.isSimulationError(sim), "expected the simulation to fail").toBe(true);`);
    if (e.contractErrorCode !== undefined) {
      assertions.push(`    if (rpc.Api.isSimulationError(sim)) expect(sim.error).toMatch(/Error\\(Contract, #${e.contractErrorCode}\\)/);`);
    }
  } else {
    assertions.push(`    if (rpc.Api.isSimulationError(sim)) throw new Error(sim.error);`);
    if (e.status === "restore_required") assertions.push(`    expect(rpc.Api.isSimulationRestore(sim)).toBe(true);`);
    else if (e.status === "success") assertions.push(`    expect(rpc.Api.isSimulationRestore(sim)).toBe(false);`);
    if (rec?.returnValue && e.returnValue !== undefined) {
      assertions.push(`    // Expected return value: ${canonicalJson(e.returnValue).slice(0, 200)}`);
      assertions.push(`    expect(sim.result?.retval.toXdr("base64")).toBe(${tsString(rec.returnValue.xdr)});`);
    }
    if (e.maxResourceFee !== undefined) {
      assertions.push(`    expect(BigInt(sim.minResourceFee)).toBeLessThanOrEqual(${e.maxResourceFee}n);`);
    }
    if (e.maxInstructions !== undefined) {
      assertions.push(`    expect(sim.transactionData.build().resources.instructions).toBeLessThanOrEqual(${e.maxInstructions});`);
    }
    if (e.contractEventCount !== undefined) {
      assertions.push(
        `    expect(sim.events.filter((ev) => ev.event.type.name === "contract")).toHaveLength(${e.contractEventCount});`,
      );
    }
    if (e.requiredAuth !== undefined) {
      assertions.push(`    expect(sim.result?.auth ?? []).toHaveLength(${e.requiredAuth.length});`);
    }
  }

  lines.push(
    `// ${scenario.name}`,
    `// Generated by the Stellar Developer Testing Playground (${scenario.createdWith ?? "unknown version"}).`,
    `// Replays a read-only simulation; nothing is signed or submitted.`,
    `// Requires: npm i -D vitest @stellar/stellar-sdk@^17`,
  );
  if (scenario.description) lines.push(commentBlock(scenario.description));
  if (fn) lines.push(`// Function: ${formatSignature(fn)}`);
  lines.push(
    `import { describe, expect, it } from "vitest";`,
    `import { Account, Operation, TransactionBuilder, rpc, xdr } from "@stellar/stellar-sdk";`,
    ``,
    `const RPC_URL = ${tsString(scenario.network.rpcUrl)};`,
    `const NETWORK_PASSPHRASE = ${tsString(scenario.network.networkPassphrase)};`,
    `const CONTRACT_ID = ${tsString(scenario.contract.id)};`,
    `const SOURCE = ${tsString(scenario.invocation.source ?? PLACEHOLDER_SOURCE)};`,
    ``,
    `// Arguments, as entered in the playground:`,
    commentBlock(JSON.stringify(scenario.invocation.args, null, 2)),
    `const ARGS = [`,
    ...argsXdr.map((a) => `  ${tsString(a)},`),
    `].map((a) => xdr.ScVal.fromXdr(a, "base64"));`,
    ``,
    `describe(${tsString(scenario.name)}, () => {`,
    `  it(${tsString(`simulates ${scenario.invocation.method}`)}, async () => {`,
    `    const server = new rpc.Server(RPC_URL, { allowHttp: RPC_URL.startsWith("http://") });`,
    `    const tx = new TransactionBuilder(new Account(SOURCE, "0"), { fee: "100", networkPassphrase: NETWORK_PASSPHRASE })`,
    `      .addOperation(Operation.invokeContractFunction({ contract: CONTRACT_ID, function: ${tsString(scenario.invocation.method)}, args: ARGS }))`,
    `      .setTimeout(0)`,
    `      .build();`,
    `    const sim = await server.simulateTransaction(tx, undefined, ${tsString(scenario.invocation.authMode)});`,
    ...assertions,
    `  }, 30_000);`,
    `});`,
    ``,
  );
  return lines.join("\n");
}

function shellQuote(s: string): string {
  return /^[A-Za-z0-9_\-.,:/@=+]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

/** Converts playground JSON to the JSON dialect `stellar contract invoke` expects (unions as `{"Case": value}`). */
export function toCliValue(value: JsonValue, type: TypeDef, spec: ContractSpec): JsonValue {
  switch (type.kind) {
    case "option":
      return value === null ? null : toCliValue(value, type.value, spec);
    case "vec":
      return Array.isArray(value) ? value.map((v) => toCliValue(v, type.element, spec)) : value;
    case "tuple":
      return Array.isArray(value) ? value.map((v, i) => (type.elements[i] ? toCliValue(v, type.elements[i]!, spec) : v)) : value;
    case "udt": {
      const udt = findUdt(spec, type.name);
      if (udt?.kind === "struct" && value && typeof value === "object" && !Array.isArray(value)) {
        return Object.fromEntries(
          Object.entries(value).map(([k, v]) => {
            const f = udt.fields.find((x) => x.name === k);
            return [k, f ? toCliValue(v, f.type, spec) : v];
          }),
        );
      }
      if (udt?.kind === "union" && value && typeof value === "object" && !Array.isArray(value) && "tag" in value) {
        const tag = String(value.tag);
        const c = udt.cases.find((x) => x.name === tag);
        const values = Array.isArray(value.values) ? value.values : [];
        if (!c || c.kind === "void") return tag;
        const converted = values.map((v, i) => (c.types[i] ? toCliValue(v, c.types[i]!, spec) : v));
        return { [tag]: converted.length === 1 ? converted[0]! : converted };
      }
      if (udt?.kind === "enum" && typeof value === "string") {
        return udt.cases.find((c) => c.name === value)?.value ?? value;
      }
      return value;
    }
    default:
      return value;
  }
}

/** A `stellar contract invoke --send=no` command reproducing the simulation with the Stellar CLI. */
export function scenarioToStellarCli(scenario: Scenario): string {
  const spec = scenario.contract.spec;
  const fn = spec?.functions.find((f) => f.name === scenario.invocation.method);
  const parts = [
    "stellar contract invoke",
    `  --id ${scenario.contract.id}`,
    `  --rpc-url ${shellQuote(scenario.network.rpcUrl)}`,
    `  --network-passphrase ${shellQuote(scenario.network.networkPassphrase)}`,
    `  --source-account ${scenario.invocation.source ?? "<your-identity>"}`,
    "  --send=no",
    `  -- ${scenario.invocation.method}`,
  ];
  for (const [name, value] of Object.entries(scenario.invocation.args)) {
    const input = fn?.inputs.find((i) => i.name === name);
    if (value === null && input?.type.kind === "option") continue;
    const cli = spec && input ? toCliValue(value, input.type, spec) : value;
    const text = typeof cli === "string" ? cli : JSON.stringify(cli);
    parts.push(`  --${name} ${shellQuote(text)}`);
  }
  return parts.join(" \\\n");
}

/** A raw JSON-RPC request, runnable with curl, for the exact transaction that was simulated. */
export function scenarioToCurl(scenario: Scenario): string {
  const txXdr = scenario.recorded?.transactionXdr;
  if (!txXdr) throw new Error("Run the scenario once to record its transaction before exporting a curl command.");
  const body = JSON.stringify({
    jsonrpc: "2.0",
    id: 1,
    method: "simulateTransaction",
    params: { transaction: txXdr, authMode: scenario.invocation.authMode },
  });
  return `curl -s -X POST ${shellQuote(scenario.network.rpcUrl)} \\\n  -H 'Content-Type: application/json' \\\n  -d ${shellQuote(body)}`;
}

/** A Markdown summary of a scenario and its last recorded result, for issues and PRs. */
export function scenarioToMarkdown(scenario: Scenario): string {
  const r = scenario.recorded?.report;
  const lines = [
    `### ${scenario.name}`,
    "",
    scenario.description ?? "",
    "",
    `- **Network:** ${scenario.network.id} (\`${scenario.network.rpcUrl}\`)`,
    `- **Contract:** \`${scenario.contract.id}\`${scenario.contract.label ? ` (${scenario.contract.label})` : ""}`,
    `- **Call:** \`${scenario.invocation.method}\``,
    "",
    "```json",
    JSON.stringify(scenario.invocation.args, null, 2),
    "```",
  ];
  if (r) {
    lines.push(
      "",
      `**Result** (ledger ${r.latestLedger}): \`${r.status}\``,
      r.returnValue ? `- Return: \`${JSON.stringify(r.returnValue.json)}\` (${r.returnValue.type})` : "",
      r.error ? `- Error: ${r.error.summary}` : "",
      r.fees ? `- Min resource fee: ${r.fees.minResourceFee} stroops` : "",
      r.resources ? `- Instructions: ${r.resources.instructions.toLocaleString("en-US")}` : "",
      `- Contract events: ${contractEvents(r).length}`,
      `- Auth entries: ${r.auth.length}`,
    );
  }
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n") + "\n";
}

// --- Share links -------------------------------------------------------------

function toBase64Url(bytes: Uint8Array): string {
  let bin = "";
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function fromBase64Url(s: string): Uint8Array {
  const b64 = s.replace(/-/g, "+").replace(/_/g, "/") + "=".repeat((4 - (s.length % 4)) % 4);
  const bin = atob(b64);
  return Uint8Array.from(bin, (c) => c.charCodeAt(0));
}

/** Streams bytes through a (de)compressor, refusing outputs larger than `maxBytes`. */
async function pipe(bytes: Uint8Array, stream: CompressionStream | DecompressionStream, maxBytes = Infinity): Promise<Uint8Array> {
  const reader = new Blob([bytes as BlobPart]).stream().pipeThrough(stream).getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.length;
    if (total > maxBytes) {
      await reader.cancel();
      throw new Error("Share link is too large.");
    }
    chunks.push(value);
  }
  const out = new Uint8Array(total);
  let offset = 0;
  for (const c of chunks) {
    out.set(c, offset);
    offset += c.length;
  }
  return out;
}

function stripDocs(spec: ContractSpec): ContractSpec {
  return JSON.parse(JSON.stringify(spec, (k, v) => (k === "doc" ? undefined : v))) as ContractSpec;
}

/** Shareable form of a scenario: expectations and spec are kept; the bulky recorded run is dropped. */
export function shareableScenario(scenario: Scenario): Scenario {
  const { recorded: _recorded, ...rest } = scenario;
  return { ...rest, contract: { ...rest.contract, spec: rest.contract.spec && stripDocs(rest.contract.spec) } };
}

export const SHARE_PREFIX = "s1.";
/** Upper bound on a decoded share payload, guarding against decompression bombs. */
export const MAX_SHARE_BYTES = 1_000_000;
/** Links longer than this may be truncated by chat apps and some browsers. */
export const SHARE_LINK_SOFT_LIMIT = 16_000;

/** Compresses a scenario into a URL-safe token for `#scenario=…` fragments (never sent to a server). */
export async function encodeShareToken(scenario: Scenario): Promise<string> {
  const json = new TextEncoder().encode(JSON.stringify(shareableScenario(scenario)));
  return SHARE_PREFIX + toBase64Url(await pipe(json, new CompressionStream("deflate-raw")));
}

/** Decodes a share token. Returns parsed JSON; validate it with `parseScenarios`. */
export async function decodeShareToken(token: string): Promise<unknown> {
  if (!token.startsWith(SHARE_PREFIX)) throw new Error("Unrecognised share link format.");
  let compressed: Uint8Array;
  try {
    compressed = fromBase64Url(token.slice(SHARE_PREFIX.length));
  } catch {
    throw new Error("Share link is corrupted (invalid base64).");
  }
  let bytes: Uint8Array;
  try {
    bytes = await pipe(compressed, new DecompressionStream("deflate-raw"), MAX_SHARE_BYTES);
  } catch (e) {
    throw new Error((e as Error).message === "Share link is too large." ? "Share link is too large." : "Share link is corrupted or truncated.");
  }
  return JSON.parse(new TextDecoder().decode(bytes));
}
